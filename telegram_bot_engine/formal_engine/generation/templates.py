def render_callback_handler(spec: FormalBotSpec) -> str:
    return '''"""Callback query router for all inline buttons."""
from __future__ import annotations
from telegram import Update
from telegram.ext import ContextTypes
from app.handlers.products import products_handler
from app.handlers.cart import cart_handler
from app.services.cart import CartService
from app.services.orders import OrderService
from app.services.catalog import CatalogService

async def callback_handler(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    query = update.callback_query
    if query is None:
        return
    await query.answer()
    data = query.data or ""
    user = update.effective_user
    uid = user.id if user else 0

    if data in ("products", "المنتجات") or "منتج" in data:
        # reuse products flow via fake message path
        if query.message:
            await query.edit_message_text("جاري عرض المنتجات...")
        # send products
        catalog = CatalogService()
        products = catalog.list_products()
        lines = ["*كتالوج المنتجات:*"]
        for p in products:
            lines.append(f"• {p['name']} — {p['price']} ج.م")
        await query.edit_message_text("\\n".join(lines), parse_mode="Markdown")
        return

    if data.startswith("add_cart:"):
        pid = data.split(":", 1)[1]
        CartService().add_item(uid, pid)
        await query.edit_message_text("✅ تمت الإضافة للسلة. استخدم /cart للعرض.")
        return

    if data in ("cart", "السلة") or data.endswith("السلة"):
        items = CartService().get_items(uid)
        if not items:
            await query.edit_message_text("السلة فارغة.")
        else:
            total = sum(i["price"] * i["qty"] for i in items)
            await query.edit_message_text(f"في السلة {len(items)} عنصر — الإجمالي {total} ج.م\\n/cart للتفاصيل")
        return

    if data == "checkout":
        order_id = OrderService().create_from_cart(uid)
        CartService().clear(uid)
        await query.edit_message_text(f"✅ تم إنشاء الطلب #{order_id}\\nسنتواصل معك قريباً.")
        return

    if data == "clear_cart":
        CartService().clear(uid)
        await query.edit_message_text("تم تفريغ السلة.")
        return

    if data.startswith("admin_"):
        await query.edit_message_text(f"قسم الإدارة: {data}\\n(قم بربط قاعدة البيانات للتشغيل الكامل)")
        return

    if data in ("main_menu", "start_action"):
        await query.edit_message_text("استخدم /start لعرض القائمة الرئيسية.")
        return

    await query.edit_message_text(f"تم اختيار: {data}")
'''


