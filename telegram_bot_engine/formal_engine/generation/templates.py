def render_cart_service(spec: FormalBotSpec) -> str:
    return '''"""In-memory cart service."""
from __future__ import annotations
from app.services.catalog import CatalogService

_CARTS: dict[int, list[dict]] = {}

class CartService:
    def get_items(self, user_id: int) -> list[dict]:
        return list(_CARTS.get(user_id, []))

    def add_item(self, user_id: int, product_id: str, qty: int = 1) -> None:
        product = CatalogService().get(product_id)
        if not product:
            return
        cart = _CARTS.setdefault(user_id, [])
        for item in cart:
            if item["id"] == product_id:
                item["qty"] += qty
                return
        cart.append({"id": product_id, "name": product["name"], "price": product["price"], "qty": qty})

    def clear(self, user_id: int) -> None:
        _CARTS[user_id] = []
'''


def render_orders_service(spec: FormalBotSpec) -> str:
    return '''"""In-memory orders service."""
from __future__ import annotations
import itertools
from app.services.cart import CartService

_ORDERS: list[dict] = []
_ID = itertools.count(1001)

class OrderService:
    def create_from_cart(self, user_id: int) -> int:
        items = CartService().get_items(user_id)
        total = sum(i["price"] * i["qty"] for i in items)
        oid = next(_ID)
        _ORDERS.append({
            "id": oid,
            "user_id": user_id,
            "items": items,
            "total": total,
            "status": "new",
        })
        return oid

    def list_user_orders(self, user_id: int) -> list[dict]:
        return [o for o in _ORDERS if o["user_id"] == user_id]

    def list_all(self) -> list[dict]:
        return list(_ORDERS)
'''


