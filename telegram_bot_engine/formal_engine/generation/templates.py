def render_requirements(spec: FormalBotSpec) -> str:
    deps = [
        "python-telegram-bot>=21.0",
        "python-dotenv>=1.0.0",
        "pydantic>=2.0",
        "pydantic-settings>=2.0",
    ]
    if spec.database.value == "postgres":
        deps.extend(["asyncpg>=0.29.0", "sqlalchemy[asyncio]>=2.0"])
    else:
        deps.append("aiosqlite>=0.20.0")
    if spec.requires_async_queue:
        deps.extend(["arq>=0.26.0", "redis>=5.0"])
    if spec.requires_payments:
        deps.append("stripe>=8.0")
    return "\n".join(sorted(set(deps))) + "\n"


def render_env_example(spec: FormalBotSpec) -> str:
    lines = [
        "TELEGRAM_BOT_TOKEN=your-bot-token-here",
        "ALLOWED_USER_IDS=",
        f"BOT_NAME={spec.bot_name}",
        "ADMIN_USER_IDS=",
        "LOG_LEVEL=INFO",
        "",
    ]
    if spec.database.value == "postgres":
        lines += ["DATABASE_URL=postgresql+asyncpg://user:pass@localhost:5432/botdb", ""]
    if spec.requires_async_queue:
        lines += ["REDIS_URL=redis://localhost:6379/0", ""]
    if spec.requires_payments:
        lines += ["STRIPE_SECRET_KEY=", "STRIPE_WEBHOOK_SECRET=", ""]
    return "\n".join(lines)


def render_config(spec: FormalBotSpec) -> str:
    return f'''"""Application configuration – strict & typed."""
from __future__ import annotations
from functools import lru_cache
from typing import Set
from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", env_file_encoding="utf-8", extra="ignore")
    telegram_bot_token: str = Field(..., min_length=30)
    allowed_user_ids: str = ""
    admin_user_ids: str = ""
    bot_name: str = "{spec.bot_name}"
    log_level: str = "INFO"
    database_url: str | None = None
    redis_url: str | None = None

    @field_validator("allowed_user_ids", "admin_user_ids", mode="before")
    @classmethod
    def _parse(cls, v: object) -> str:
        return "" if v is None else str(v)

    def _ids(self, raw: str) -> Set[int]:
        if not raw.strip():
            return set()
        return {{int(x.strip()) for x in raw.split(",") if x.strip().isdigit()}}

    @property
    def allowed_ids(self) -> Set[int]:
        return self._ids(self.allowed_user_ids)

    @property
    def admin_ids(self) -> Set[int]:
        return self._ids(self.admin_user_ids)

@lru_cache
def get_settings() -> Settings:
    return Settings()
'''


def _cmd_handlers_imports(spec: FormalBotSpec) -> str:
    cmds = [c.command for c in spec.ui.commands]
    lines = ["from app.handlers.start import start_handler, help_handler"]
    if "products" in cmds or spec.bot_type.value == "ecommerce":
        lines.append("from app.handlers.products import products_handler")
    if "cart" in cmds or spec.bot_type.value == "ecommerce":
        lines.append("from app.handlers.cart import cart_handler")
    if "orders" in cmds or spec.bot_type.value == "ecommerce":
        lines.append("from app.handlers.orders import orders_handler")
    if "admin" in cmds or spec.requires_admin_panel:
        lines.append("from app.handlers.admin import admin_handler")
    lines.append("from app.handlers.callbacks import callback_handler")
    lines.append("from app.handlers.messages import message_handler")
    return "\n".join(lines)


def _cmd_registrations(spec: FormalBotSpec) -> str:
    lines = [
        '    app.add_handler(CommandHandler("start", start_handler))',
        '    app.add_handler(CommandHandler("help", help_handler))',
    ]
    cmds = {c.command for c in spec.ui.commands}
    if "products" in cmds or spec.bot_type.value == "ecommerce":
        lines.append('    app.add_handler(CommandHandler("products", products_handler))')
    if "cart" in cmds or spec.bot_type.value == "ecommerce":
        lines.append('    app.add_handler(CommandHandler("cart", cart_handler))')
    if "orders" in cmds or spec.bot_type.value == "ecommerce":
        lines.append('    app.add_handler(CommandHandler("orders", orders_handler))')
    if "admin" in cmds or spec.requires_admin_panel:
        lines.append('    app.add_handler(CommandHandler("admin", admin_handler))')
    # register any other custom commands generically via messages for now
    lines.append("    app.add_handler(CallbackQueryHandler(callback_handler))")
    lines.append("    app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, message_handler))")
    return "\n".join(lines)


