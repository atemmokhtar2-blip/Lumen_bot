def render_start_handler(spec: FormalBotSpec) -> str:
    rows = []
    for b in (spec.ui.main_buttons or [])[:8]:
        text = b.text.replace("\\", "\\\\").replace('"', '\\"')
        cb = b.callback_data.replace('"', '\\"')
        rows.append(f'        [InlineKeyboardButton("{text}", callback_data="{cb}")]' )
    if not rows:
        rows = ['        [InlineKeyboardButton("🏠 القائمة", callback_data="main_menu")]']
    buttons_code = ",\n".join(rows)
    welcome = (spec.ui.welcome_message or ("مرحبا بك في " + spec.bot_name))
    welcome = welcome.replace('"""', "'''")
    cmd_lines = "\\n".join(f"/{c.command} — {c.description}" for c in spec.ui.commands) or "/start — تشغيل"
    return (
        '"""Start / help handlers with main menu buttons."""\n'
        "from __future__ import annotations\n"
        "from telegram import InlineKeyboardButton, InlineKeyboardMarkup, Update\n"
        "from telegram.constants import ParseMode\n"
        "from telegram.ext import ContextTypes\n\n\n"
        "def _main_keyboard() -> InlineKeyboardMarkup:\n"
        "    keyboard = [\n"
        + buttons_code + "\n"
        "    ]\n"
        "    return InlineKeyboardMarkup(keyboard)\n\n\n"
        "async def start_handler(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:\n"
        "    message = update.effective_message\n"
        "    if message is None:\n"
        "        return\n"
        "    text = " + repr(welcome) + "\n"
        "    await message.reply_text(text, parse_mode=ParseMode.MARKDOWN, reply_markup=_main_keyboard())\n\n\n"
        "async def help_handler(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:\n"
        "    message = update.effective_message\n"
        "    if message is None:\n"
        "        return\n"
        "    text = " + repr("*الأوامر المتاحة:*\n" + cmd_lines.replace("\\n", "\n")) + "\n"
        "    await message.reply_text(text, parse_mode=ParseMode.MARKDOWN, reply_markup=_main_keyboard())\n"
    )


